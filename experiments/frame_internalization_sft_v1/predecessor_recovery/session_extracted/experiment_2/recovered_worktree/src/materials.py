# ---------------------------------------------------------------------------
# Conversation assembler.
# ---------------------------------------------------------------------------
def build_messages(
    *,
    stressor: str,          # "S1" | "S2" | "S3"
    variant: str,           # S1: "4" | "10"; S2: "generic" | "targeted"; S3: "practice"
    frame: str,
    tier: str,
    harmful_text: str,
    practice_transcript: list[dict] | None = None,  # required for S3: flat user/assistant msgs
) -> list[dict]:
    """Return an OpenAI-style messages list for one (stressor, variant, frame, tier, query)."""
    msgs: list[dict] = [{"role": "system", "content": system_prompt(frame)}]
    tmpl = tier_template(tier)

    if stressor == "S1":
        n = int(variant)
        msgs += filler_turns(n)
        final_user = tmpl.replace("{user_input}", harmful_text)
        msgs.append({"role": "user", "content": final_user})

    elif stressor == "S2":
        if variant == "generic":
            override = OVERRIDE_GENERIC
        elif variant == "targeted":
            if frame == "F0":
                override = OVERRIDE_GENERIC  # no frame to target; F0 targeted == generic
            else:
                override = OVERRIDE_TARGETED[frame]
        else:
            raise ValueError(variant)
        # override precedes the harmful query, inside the tier-tagged test turn
        user_input = override + "\n\n" + harmful_text
        final_user = tmpl.replace("{user_input}", user_input)
        msgs.append({"role": "user", "content": final_user})

    elif stressor == "S3":
        assert practice_transcript is not None, "S3 requires a practice_transcript"
        msgs += practice_transcript
        final_user = tmpl.replace("{user_input}", harmful_text)
        msgs.append({"role": "user", "content": final_user})

    else:
        raise ValueError(stressor)

    return msgs


