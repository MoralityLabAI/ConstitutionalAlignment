def filler_turns(n_turns: int) -> list[dict]:
    """Return the first n_turns benign exchanges as a flat messages list."""
    assert n_turns <= len(FILLER), f"only {len(FILLER)} filler exchanges available"
    msgs = []
    for u, a in FILLER[:n_turns]:
        msgs.append({"role": "user", "content": u})
        msgs.append({"role": "assistant", "content": a})
    return msgs


