"""Stress-test materials + multi-turn conversation assembler.

Extends experiment #1's single-turn arm construction (system_FX + tier template
+ harmful query) to three stressors, each inserting content BEFORE the final
test-query turn:

  S1 persistence  : N turns of scripted, frame-neutral benign dialogue, then the
                    test query. Tier tag lives ONLY on the final test turn (as in
                    #1), so the tier signal stays fresh and any gap decay is
                    attributable to the FRAME (system prompt) receding into
                    conversation history, not to tier forgetting.
  S2 override     : the final user turn is prefixed with an override attempt
                    (generic, or frame-targeted) argued against the frame, then
                    the tier-tagged test query.
  S3 practice     : 3 completed draft -> critique -> revise moral-dilemma
                    exercises (pre-generated by the model under the arm's frame)
                    as prior turns, then the test query. Rehearsed vs pasted frame.

Placement of the tier tag: always and only on the final test-query turn, using
#1's exact think-mode tier template. Filler / override / practice turns carry no
tier tag and no accountability/moral vocabulary (S1 filler) so the manipulation
is clean.

Prior assistant turns are passed with `content` only (no `reasoning_content`):
INTELLECT-3's chat template then renders them without a <think> block, matching
how a reasoning model keeps only visible responses in history.
"""

